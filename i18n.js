function springState(time, initial, target, velocity, response, damping) {
  const omega = 2 * Math.PI / response;
  const decay = damping * omega;
  const frequency = omega * Math.sqrt(1 - damping * damping);
  const distance = initial - target;
  const sineCoefficient = (velocity + decay * distance) / frequency;
  const envelope = Math.exp(-decay * time);
  const cosine = Math.cos(frequency * time);
  const sine = Math.sin(frequency * time);
  return {
    value: target + envelope * (distance * cosine + sineCoefficient * sine),
    velocity: envelope * (
      (frequency * sineCoefficient - decay * distance) * cosine -
      (frequency * distance + decay * sineCoefficient) * sine
    )
  };
}

function createLanguageMenuFrames() {
  // Match the stash hover's 140ms impulse and its softer return spring.
  // Preserve velocity when retargeting; no pause at the expansion peak.
  const impulse = springState(.14, .9, 1.025, 0, .2, .55);
  return Array.from({length:83}, (_, index) => {
    const offset = index / 82;
    const time = offset * .68;
    const scale = time <= .14
      ? springState(time, .9, 1.025, 0, .2, .55).value
      : springState(time - .14, impulse.value, 1, impulse.velocity, .34, .45).value;
    const y = springState(time, -5, 0, 0, .24, .62).value;
    const reveal = Math.min(1, time / .12);
    return {
      offset,
      opacity: reveal * reveal * (3 - 2 * reveal),
      transform: index === 82 ? 'translateY(0) scale(1)' : `translateY(${y}px) scale(${scale})`
    };
  });
}
const languageMenuFrames = createLanguageMenuFrames();

function renderLocalizedText(element, value) {
  element.replaceChildren();
  (Array.isArray(value) ? value : [value]).forEach((line, index) => {
    if (index) element.append(document.createElement('br'));
    element.append(document.createTextNode(line));
  });
}

// Invisible grid peers reserve each text row's largest translated height.
// Normal layout handles viewport and font changes without fixed pixel heights.
function reserveIntroSpace() {
  const fields = [...intro.querySelectorAll('[data-i18n]')];
  for (const [language, copy] of Object.entries(messages)) {
    for (const field of fields) {
      const measurement = field.cloneNode(false);
      measurement.removeAttribute('data-i18n');
      measurement.removeAttribute('id');
      measurement.classList.add('intro-measure');
      measurement.lang = language;
      measurement.setAttribute('aria-hidden', 'true');
      measurement.inert = true;
      renderLocalizedText(measurement, copy[field.dataset.i18n]);
      intro.append(measurement);
    }
  }
}

function applyLanguage(language) {
  language = normalizeLanguage(language);
  const copy = messages[language];
  document.documentElement.lang = language;
  document.querySelector('#language-current').textContent = languageNames[language];
  languageOptions.forEach(option => option.setAttribute('aria-checked', String(option.dataset.language === language)));
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const value = copy[element.dataset.i18n];
    if (value === undefined) return;
    renderLocalizedText(element, value);
    if (element.parentElement === intro) element.lang = language;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(element => {
    element.setAttribute('aria-label', copy[element.dataset.i18nAria]);
  });
  document.querySelectorAll('[data-screenshot]').forEach(image => {
    const name = image.dataset.screenshot;
    const path = `assets/${language.toLowerCase()}/${name}.png`;
    if (image.getAttribute('src') !== path) image.setAttribute('src', path);
    image.alt = copy[screenshotLabels[name]];
  });
  document.title = `Vorlinx · ${copy.tagline}`;
  document.querySelector('meta[name="description"]').content = [...copy.heroCopy].join(' ');
  const url = new URL(location.href);
  url.searchParams.set('lang', language);
  history.replaceState(null, '', url);
  currentLanguage = language;
}

async function fadeLanguageContent(from, to) {
  if (reducedMotion.matches) return;
  const targets = document.querySelectorAll('[data-i18n]:not(.sr-only), .hero-shot>[data-screenshot]');
  const animations = [...targets].map(element => {
    const animation = element.animate([{opacity:from}, {opacity:to}], {
      duration:to > from ? 640 : 360,
      easing:'cubic-bezier(.37, 0, .63, 1)',
      fill:'forwards'
    });
    languageAnimations.add(animation);
    return animation;
  });
  await Promise.all(animations.map(animation => animation.finished.catch(() => {})));
}

async function prepareHeroImage(language) {
  const image = new Image();
  const name = document.querySelector('.hero-shot>[data-screenshot]').dataset.screenshot;
  image.src = `assets/${language.toLowerCase()}/${name}.png`;
  // Decoding first avoids showing an empty frame while a new image loads.
  // A missing replacement image must not prevent changing the site's language.
  await image.decode().catch(() => {});
}

async function changeLanguage(language) {
  requestedLanguage = normalizeLanguage(language);
  if (languageSwitchRunning || requestedLanguage === currentLanguage) return;
  languageSwitchRunning = true;
  intro.setAttribute('aria-busy', 'true');
  try {
    while (requestedLanguage !== currentLanguage) {
      let preparedLanguage = requestedLanguage;
      let preparation = prepareHeroImage(preparedLanguage);
      document.body.dataset.languageTransition = 'fading-out';
      await fadeLanguageContent(1, 0);
      document.body.dataset.languageTransition = 'loading-image';
      // Keep following the latest selection, including while decoding images.
      while (true) {
        await preparation;
        if (preparedLanguage === requestedLanguage) break;
        preparedLanguage = requestedLanguage;
        preparation = prepareHeroImage(preparedLanguage);
      }
      applyLanguage(preparedLanguage);
      await document.querySelector('.hero-shot>[data-screenshot]').decode().catch(() => {});
      document.body.dataset.languageTransition = 'fading-in';
      await fadeLanguageContent(0, 1);
      for (const animation of languageAnimations) animation.cancel();
      languageAnimations.clear();
    }
  } finally {
    for (const animation of languageAnimations) animation.cancel();
    languageAnimations.clear();
    delete document.body.dataset.languageTransition;
    intro.setAttribute('aria-busy', 'false');
    languageSwitchRunning = false;
  }
}

reducedMotion.addEventListener('change', event => {
  if (event.matches) {
    for (const animation of languageAnimations) animation.finish();
    languageMenuAnimation?.cancel();
    languageMenuAnimation = null;
  }
});
function setLanguageMenuOpen(open, focusIndex = null) {
  const opening = open && languageMenu.hidden;
  if (!open) {
    languageMenuAnimation?.cancel();
    languageMenuAnimation = null;
  }
  languageMenu.hidden = !open;
  languageTrigger.setAttribute('aria-expanded', String(open));
  if (opening && !reducedMotion.matches) {
    const animation = languageMenu.animate(languageMenuFrames, {duration:680, easing:'linear'});
    languageMenuAnimation = animation;
    animation.onfinish = () => {
      if (languageMenuAnimation === animation) languageMenuAnimation = null;
    };
  }
  if (open && focusIndex !== null) languageOptions[focusIndex].focus();
}
languageControl.addEventListener('pointerenter', event => {
  if (event.pointerType === 'mouse' || event.pointerType === 'pen') setLanguageMenuOpen(true);
});
languageControl.addEventListener('pointerleave', event => {
  if (event.pointerType === 'mouse' || event.pointerType === 'pen') setLanguageMenuOpen(false);
});
languageTrigger.addEventListener('click', event => {
  const selected = languageOptions.findIndex(option => option.getAttribute('aria-checked') === 'true');
  setLanguageMenuOpen(true, event.detail === 0 ? Math.max(0, selected) : null);
});
languageTrigger.addEventListener('keydown', event => {
  if (event.key === 'ArrowDown' || event.key === 'ArrowUp') {
    event.preventDefault();
    setLanguageMenuOpen(true, event.key === 'ArrowDown' ? 0 : languageOptions.length - 1);
  }
});
languageOptions.forEach(option => option.addEventListener('click', () => {
  void changeLanguage(option.dataset.language);
  setLanguageMenuOpen(false);
  languageTrigger.focus();
}));
languageMenu.addEventListener('keydown', event => {
  const index = languageOptions.indexOf(document.activeElement);
  let target;
  if (event.key === 'ArrowDown') target = (index + 1) % languageOptions.length;
  if (event.key === 'ArrowUp') target = (index - 1 + languageOptions.length) % languageOptions.length;
  if (event.key === 'Home') target = 0;
  if (event.key === 'End') target = languageOptions.length - 1;
  if (target !== undefined) {
    event.preventDefault();
    languageOptions[target].focus();
  }
});
